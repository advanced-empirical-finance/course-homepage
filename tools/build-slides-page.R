#!/usr/bin/env Rscript
# Copies the rendered lecture decks from the sibling course-repository into
# slides/ and (re)generates the embedded Slides page (slides.qmd).
#
# Wired as a Quarto pre-render hook (see _quarto.yml), so it runs automatically
# on every `quarto render` / `quarto preview`. The decks are treated as opaque,
# already-rendered, self-contained HTML -- nothing here executes R/Python.

source_dir <- Sys.getenv("SLIDES_SRC", "../course-repository/lecture-slides")
dest_dir   <- "slides"
out_qmd    <- "slides.qmd"

if (!dir.exists(source_dir)) {
  stop(sprintf("Source slides folder not found: %s", normalizePath(source_dir, mustWork = FALSE)))
}

# Fresh copy of the decks (drop stale ones that no longer exist upstream).
if (dir.exists(dest_dir)) {
  old <- list.files(dest_dir, pattern = "\\.(html|pdf)$", full.names = TRUE)
  if (length(old)) invisible(file.remove(old))
} else {
  dir.create(dest_dir, recursive = TRUE)
}

# One deck per lecture: aef-NN-<topic>.html, NN the lecture number. The older
# decks in the course repository hold material that moves into these and stay
# off the homepage. Live versions (<deck>.live.html, quarto ... --profile live)
# are for the lecturer only and never published.
decks <- sort(list.files(source_dir, pattern = "^aef-[0-9]{2}-.*\\.html$"))
decks <- decks[!grepl("\\.live\\.html$", decks)]
if (length(decks) == 0) stop(sprintf("No .html decks found in %s", source_dir))
invisible(file.copy(file.path(source_dir, decks), file.path(dest_dir, decks), overwrite = TRUE))
# Every deck also comes as PDF (Quarto renders both formats)
pdfs <- sub("\\.html$", ".pdf", decks)
pdfs <- pdfs[file.exists(file.path(source_dir, pdfs))]
invisible(file.copy(file.path(source_dir, pdfs), file.path(dest_dir, pdfs), overwrite = TRUE))
cat(sprintf("Copied %d deck(s) and %d PDF(s) to %s\n", length(decks), length(pdfs), dest_dir))

# The heading of a deck is its subtitle, the lecture's title in the lecture
# plan; without a .qmd next to it, the file name.
deck_title <- function(stem) {
  qmd <- file.path(source_dir, paste0(stem, ".qmd"))
  if (file.exists(qmd)) {
    subtitle <- grep("^subtitle:", readLines(qmd, n = 20, warn = FALSE), value = TRUE)
    if (length(subtitle)) return(trimws(gsub('^subtitle:|"', "", subtitle[1])))
  }
  gsub("-", " ", sub("^aef-[0-9]+-", "", stem))
}

lines <- c(
  "---",
  "title: Slides",
  "---",
  "",
  "<!-- GENERATED by tools/build-slides-page.R -- do not edit by hand. -->",
  "",
  "Each lecture deck is embedded below. Click a deck and use its own controls",
  "(or the arrow keys) to navigate, or open it full screen. Download it as HTML",
  "(the slides as shown in the lecture) or as PDF (to print and annotate).",
  ""
)

for (f in decks) {
  stem  <- sub("\\.html$", "", f)
  title <- deck_title(stem)
  src   <- paste0("slides/", f)
  lines <- c(lines,
    sprintf("## %s {#%s}", title, stem),
    "",
    "::: {.ratio .ratio-16x9 .slide-embed}",
    "```{=html}",
    sprintf('<iframe src="%s" title="%s" loading="lazy" allowfullscreen></iframe>', src, title),
    "```",
    ":::",
    "",
    "```{=html}",
    sprintf('<a class="btn btn-sm btn-outline-primary" href="%s" target="_blank" rel="noopener">Open full screen &#8599;</a>', src),
    sprintf('<a class="btn btn-sm btn-outline-secondary" href="%s" download>HTML &#8595;</a>', src),
    if (file.exists(file.path(dest_dir, sub("\\.html$", ".pdf", f)))) {
      sprintf('<a class="btn btn-sm btn-outline-secondary" href="%s" download>PDF &#8595;</a>', sub("\\.html$", ".pdf", src))
    },
    "```",
    ""
  )
}

lines <- c(lines,
  "```{=html}",
  "<style>",
  "  .slide-embed { border: 1px solid var(--bs-border-color); border-radius: .375rem; overflow: hidden; margin-bottom: .5rem; }",
  "  .slide-embed iframe { width: 100%; height: 100%; border: 0; }",
  "</style>",
  "```"
)

writeLines(lines, out_qmd)
cat(sprintf("Wrote %s\n", out_qmd))
